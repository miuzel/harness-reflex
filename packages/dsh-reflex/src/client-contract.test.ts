import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';

import { ALLOWED_SEEDS, BUNDLE_RELATIVE_PATH, CLIENT_BUNDLE_ID, collectRequires } from './client-bundle.js';
import { REFLEX_PLUGIN_VERSION } from './panel-api.js';

/**
 * The two halves of this plugin meet at a manifest, not at an import: the Host
 * build must publish a browser bundle that the DSH client loader can find, load,
 * and resolve. Nothing in either half's own tests can catch a manifest that
 * declares the wrong export path, forgets the artifact from `files`, or injects
 * a client module that does not exist — a mistake there is invisible until a
 * real `web boot` refuses to start. These assertions pin that seam.
 *
 * The artifact itself is generated by `npm run build:plugin-client`, so this
 * suite reads the committed output exactly as the loader would.
 */

const packageRoot = fileURLToPath(new URL('..', import.meta.url));

/** The package manifest, as published. */
function manifest(): Record<string, unknown> {
  return JSON.parse(readFileSync(join(packageRoot, 'package.json'), 'utf8')) as Record<string, unknown>;
}

/** The generated browser bundle. */
function bundleText(): string {
  return readFileSync(join(packageRoot, BUNDLE_RELATIVE_PATH), 'utf8');
}

/** The `dsh.client` declaration of the manifest. */
function clientDeclaration(): Record<string, unknown> {
  const declared = (manifest().dsh as Record<string, unknown> | undefined)?.client;
  assert.ok(typeof declared === 'object' && declared !== null, 'package.json declares no dsh.client');
  return declared as Record<string, unknown>;
}

/** The `node_modules` directory holding the DSH packages, when one is linked. */
function dshModulesDirectory(): string | undefined {
  try {
    const require = createRequire(import.meta.url);
    const entry = require.resolve('@deepseek-ai/dsh-client-modules/package.json');
    return dirname(dirname(dirname(entry)));
  } catch {
    return undefined;
  }
}

test('the manifest publishes the browser half as a client module', () => {
  const pkg = manifest();
  const client = clientDeclaration();

  assert.equal(pkg.name, 'dsh-harness-reflex');
  assert.equal(client.platform, 'web');
  // The activation switch: without an exports map the package is not scanned at
  // all, and without this subpath the loader throws for a declared dsh.client.
  const exports = pkg.exports as Record<string, unknown>;
  assert.equal(exports['./client'], './client.js');
  assert.equal((exports['.'] as Record<string, string>)?.default, './dist/index.js', 'the Host entry moved');
  // A published package that omits the artifact ships a plugin that cannot load.
  const files = pkg.files as string[];
  assert.ok(files.includes('client.js'), 'client.js is not published');
  assert.ok(files.some((entry) => entry.startsWith('dist/')), 'the Host half is not published');
  assert.ok(files.some((entry) => entry.startsWith('!dist/') && entry.includes('.test.')), 'test builds would be published');
});

test('the artifact is a client module the loader can recognise', () => {
  assert.ok(existsSync(join(packageRoot, BUNDLE_RELATIVE_PATH)), `${BUNDLE_RELATIVE_PATH} is missing; run npm run build:plugin-client`);
  const text = bundleText();

  // An empty or truncated bundle would activate and register nothing, which a
  // real boot reports as a plugin that does nothing rather than as an error.
  assert.ok(text.length > 10_000, `the bundle is suspiciously small (${String(text.length)} bytes)`);
  assert.ok(text.includes('__ModuleLoader__'), 'the bundle does not talk to the module loader');
  assert.ok(text.includes(CLIENT_BUNDLE_ID), 'the bundle does not declare its module id');
  assert.ok(text.includes('settings.section'), 'the bundle does not register into a settings slot');
  assert.ok(text.includes('settings'), 'the bundle declares no settings surface');
});

test('the bundle requires only the specifiers the manifest declares external', () => {
  const text = bundleText();
  const required = [...new Set(collectRequires(text))].sort();
  // Relative specifiers name modules inside the bundle; anything else must be
  // declared, because the loader resolves a bare id from its own module table.
  const platform = required.filter((specifier) => !specifier.startsWith('.'));
  const external = [...((clientDeclaration().external as string[] | undefined) ?? [])].sort();

  assert.deepEqual(platform, external, 'dsh.client.external and the bundle disagree');
  assert.ok(required.length > platform.length, 'the bundle inlined no sibling module; it is not self-contained');
  for (const specifier of required) {
    if (!specifier.startsWith('.')) assert.ok(ALLOWED_SEEDS.includes(specifier), `"${specifier}" is not a platform seed word`);
  }
});

test('the injected client modules are declared client modules of this platform', (context) => {
  const modules = dshModulesDirectory();
  if (modules === undefined) {
    // Injecting an id the boot graph does not know leaves its module `pending`,
    // and one pending entry aborts the whole `web boot` — so this is the check
    // that matters most, and it needs an installed DSH to be meaningful.
    context.skip('no DSH installation is linked in this checkout');
    return;
  }
  const inject = clientDeclaration().inject as string[];
  assert.ok(inject.length > 0, 'the client declares no consumed client modules');

  for (const id of inject) {
    const manifestPath = join(modules, ...id.split('/'), 'package.json');
    assert.ok(existsSync(manifestPath), `dsh.client.inject names "${id}", which is not an installed package`);
    const declared = (JSON.parse(readFileSync(manifestPath, 'utf8')) as { name: string; dsh?: { client?: { platform?: string } } });
    assert.equal(declared.name, id);
    assert.equal(declared.dsh?.client?.platform, 'web', `"${id}" is not a web client module; booting would stall on it`);
  }
  // Dependency direction: a client module must not inject itself.
  assert.equal(inject.includes(CLIENT_BUNDLE_ID), false);
  assert.equal(new Set(inject).size, inject.length, 'a client module is injected twice');
});

test('the reported plugin version is the published one', () => {
  assert.equal(REFLEX_PLUGIN_VERSION, manifest().version);
});

test('the locale namespace the client registers is the one the host documents', () => {
  // The panel's copy lives entirely in the browser bundle; the namespace is the
  // only part of it the Host side can be held to.
  const text = bundleText();
  assert.ok(text.includes('dsh-reflex.panel'), 'the bundle does not register its locale namespace');
  assert.match(text, /\bzh\s*:/, 'the bundle carries no zh dictionary');
  assert.match(text, /\ben\s*:/, 'the bundle carries no en dictionary');
});

test('the bundle keeps every dependency at the platform seed boundary', () => {
  const text = bundleText();
  const required = collectRequires(text);
  // A bundle that reaches for a Node builtin cannot run in the browser realm.
  for (const specifier of required) {
    assert.equal(specifier.startsWith('node:'), false, `the bundle requires the Node builtin "${specifier}"`);
  }
  assert.equal(text.includes('require("node:'), false);
  assert.equal(text.includes("require('node:"), false);
});
